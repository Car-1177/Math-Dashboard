function CodeBlock({ code, lang }: { code: string; lang: string }) {
  const [copied, setCopied] = useState(false);
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(code);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1500);
    } catch {
      /* clipboard blocked */
    }
  };
  return (
    <div className="relative overflow-hidden rounded-xl border border-slate-700 bg-slate-950">
      <div className="flex items-center justify-between border-b border-slate-800 px-3 py-1.5">
        <span className="font-mono text-xs uppercase tracking-wide text-slate-500">{lang}</span>
        <button
          onClick={copy}
          className="flex items-center gap-1 rounded px-2 py-0.5 text-xs text-slate-400 hover:bg-slate-800 hover:text-white"
        >
          {copied ? <Check className="h-3.5 w-3.5 text-emerald-400" /> : <Copy className="h-3.5 w-3.5" />}
          {copied ? "Copied" : "Copy"}
        </button>
      </div>
      <pre className="overflow-x-auto p-4 text-xs leading-relaxed text-slate-200">
        <code>{code}</code>
      </pre>
    </div>
  );
}

const SQL_SCHEMA = `-- Run this in Supabase -> SQL Editor -> New query

-- 1. Profiles (extends auth.users)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  avatar_url text,
  created_at timestamptz default now()
);

-- 2. Community questions
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  author_id uuid references public.profiles(id) on delete cascade,
  author_name text not null,
  topic text not null,
  title text not null,
  body text not null,
  votes int not null default 0,
  solved boolean not null default false,
  created_at timestamptz default now()
);

-- 3. Answers
create table if not exists public.replies (
  id bigint generated by default as identity primary key,
  post_id bigint references public.posts(id) on delete cascade,
  author_id uuid references public.profiles(id) on delete cascade,
  author_name text not null,
  text text not null,
  votes int not null default 0,
  accepted boolean not null default false,
  created_at timestamptz default now()
);

-- 4. Study planner tasks (per user)
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  text text not null,
  subject text not null default 'Algebra',
  done boolean not null default false,
  created_at timestamptz default now()
);

-- 5. Row Level Security - everyone reads, only owners write
alter table public.profiles enable row level security;
alter table public.posts    enable row level security;
alter table public.replies  enable row level security;
alter table public.tasks    enable row level security;

create policy "profiles readable" on public.profiles for select using (true);
create policy "own profile write" on public.profiles for all using (auth.uid() = id);

create policy "posts readable" on public.posts for select using (true);
create policy "posts insert"   on public.posts for insert with check (auth.uid() = author_id);
create policy "posts update"   on public.posts for update using (auth.uid() = author_id);

create policy "replies readable" on public.replies for select using (true);
create policy "replies insert"   on public.replies for insert with check (auth.uid() = author_id);
create policy "replies update"   on public.replies for update using (true);

create policy "tasks owner only" on public.tasks for all using (auth.uid() = user_id);

-- 6. Auto-create a profile when someone signs up
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer as $$
begin
  insert into public.profiles (id, username)
  values (new.id, coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)));
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();`;

